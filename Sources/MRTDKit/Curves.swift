import Foundation

/// Affine point on a short Weierstrass curve; coordinates are big-endian, field-length bytes.
public struct ECPoint: Equatable {
    public let x: Bytes
    public let y: Bytes
    public let isInfinity: Bool

    public static let infinity = ECPoint(x: [], y: [], isInfinity: true)

    public init(x: Bytes, y: Bytes) {
        self.x = x
        self.y = y
        isInfinity = false
    }

    private init(x: Bytes, y: Bytes, isInfinity: Bool) {
        self.x = x
        self.y = y
        self.isInfinity = isInfinity
    }
}

